export function getIngredientEmoji(name) {
  if (!name) return '🛒';
  const clean = name.trim();
  const found = INGREDIENTS_500.find(ing => ing.name === clean);
  if (found) return found.emoji;
  for (const ing of INGREDIENTS_500) {
    if (ing.name.includes(clean) || clean.includes(ing.name)) return ing.emoji;
  }
  return '🛒';
}