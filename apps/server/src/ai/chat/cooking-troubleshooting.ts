/** Normalize a token/prompt the same way for substring matching (fold + drop ZWNJ so «ته‌دیگ»≈«تهدیگ»). */
const norm = (s: string) => foldPersian(s).replace(/‌/g, '');

/**
 * Find the best-matching troubleshooting entry for a free «چرا ... شد؟» prompt, or null if none fits.
 * Requires a SYMPTOM hit, plus a DISH hit unless the entry is general (dish:[]). Specific-dish entries and
 * more token hits win.
 */
export function matchTroubleshooting(prompt: unknown): TroubleshootEntry | null {
  const p = norm(String(prompt ?? ''));
  if (!p) return null;
  let best: { entry: TroubleshootEntry; score: number } | null = null;
  for (const entry of TROUBLESHOOTING) {
    const symptomHits = entry.symptom.filter((s) => p.includes(norm(s))).length;
    if (symptomHits === 0) continue;
    const dishHits = entry.dish.filter((d) => p.includes(norm(d))).length;
    if (entry.dish.length > 0 && dishHits === 0) continue; // a dish-specific entry needs its dish named
    // specific-dish entries strongly preferred over general ones; then by total token hits
    const score = (entry.dish.length > 0 ? 100 : 0) + dishHits * 10 + symptomHits;
    if (!best || score > best.score) best = { entry, score };
  }
  return best ? best.entry : null;
}
